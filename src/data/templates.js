export const TEMPLATES = RAW_TEMPLATES.map((tpl, idx) => normalizeTemplate(tpl, idx));

export function getTemplateById(id) {
  return TEMPLATES.find((t) => t.id === id) || TEMPLATES[0];
}

export function getTemplatesByCategoryBreakdown() {
  const breakdown = {};
  for (const cat of TEMPLATE_CATEGORIES) {
    if (cat.id === 'all') {
      breakdown[cat.id] = TEMPLATES.length;
    } else {
      breakdown[cat.id] = TEMPLATES.filter((t) => t.categories.includes(cat.id)).length;
    }
  }
  return breakdown;
}
